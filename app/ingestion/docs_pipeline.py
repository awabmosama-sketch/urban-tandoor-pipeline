"""Document pipeline: DOCX + menu narratives -> JSON -> MongoDB.

Two logical source documents are produced:

* ``docx:urban_tandoor_profile`` — the restaurant profile split into chunks.
* ``menu:catalog_narratives`` — one synthetic chunk per menu item.

The JSON files contain text and metadata only. Embeddings are generated by the
MongoDB importer, so the JSON stays small and embeddings always match the
currently configured provider.
"""

from __future__ import annotations

import hashlib
from datetime import UTC, datetime
from pathlib import Path

from app.config import get_settings
from app.ingestion.chunker import chunk_sections
from app.ingestion.docx_loader import load_docx_sections
from app.ingestion.json_store import has_collection, read_collection, write_collection

PROFILE_DOCX_FILENAME = "Urban_Tandoor_Grill_Restaurant_Profile.docx"


def _sha256_of_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _sha256_of_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _profile_source_document(docx_path: Path) -> dict:
    return {
        "document_id": "docx:urban_tandoor_profile",
        "source_path": str(docx_path),
        "source_type": "docx",
        "checksum": _sha256_of_file(docx_path),
        "title": "Urban Tandoor & Grill — Restaurant Profile",
        "loaded_at": datetime.now(UTC),
        "metadata_json": {},
    }


def _menus_narrative_source_document(menu_rows: list[dict]) -> dict:
    parts = [
        f"{row['menu_id']}|{row['item_name']}|{row['category']}|"
        f"{row.get('dietary_hint') or ''}|{row.get('allergen_hint') or ''}|"
        f"{row['base_price_pkr']}|{row['prep_time_min']}"
        for row in menu_rows
    ]
    return {
        "document_id": "menu:catalog_narratives",
        "source_path": "<synthetic:menu_items>",
        "source_type": "xlsx_sheet",
        "checksum": _sha256_of_text("\n".join(parts)),
        "title": "Menu catalog narratives (one chunk per menu item)",
        "loaded_at": datetime.now(UTC),
        "metadata_json": {},
    }


def _build_profile_chunks(docx_path: Path) -> list[dict]:
    settings = get_settings()
    sections = load_docx_sections(docx_path)
    chunks = chunk_sections(
        sections,
        chunk_size=settings.chunk_size,
        overlap=settings.chunk_overlap,
    )
    document_id = "docx:urban_tandoor_profile"
    return [
        {
            "chunk_id": f"{document_id}:{index:04d}",
            "document_id": document_id,
            "ordinal": index,
            "content": chunk["content"],
            "token_count": int(chunk.get("token_count") or 0),
            "section": chunk.get("section"),
            "metadata_json": {"section": chunk.get("section")},
        }
        for index, chunk in enumerate(chunks)
    ]


def _build_menu_narrative_chunks(menu_rows: list[dict]) -> list[dict]:
    document_id = "menu:catalog_narratives"
    chunks: list[dict] = []
    for index, row in enumerate(sorted(menu_rows, key=lambda item: item["menu_id"])):
        content = (
            f"{row['menu_id']} {row['item_name']}. "
            f"Category: {row['category']}. "
            f"Description: {row.get('description') or 'traditional preparation'}. "
            f"Dietary hint: {row.get('dietary_hint') or 'not verified'}. "
            f"Allergen hint: {row.get('allergen_hint') or 'not verified'}. "
            f"Base price PKR {float(row['base_price_pkr']):.2f}. "
            f"Preparation time {row['prep_time_min']} minutes. "
            f"Service window: {row['service_window']}."
        )
        chunks.append(
            {
                "chunk_id": f"{document_id}:{index:04d}",
                "document_id": document_id,
                "ordinal": index,
                "content": content,
                "token_count": len(content.split()),
                "section": row["category"],
                "metadata_json": {"section": row["category"]},
            }
        )
    return chunks


def _menu_rows_for_narratives() -> list[dict]:
    if has_collection("menu_items"):
        return read_collection("menu_items")
    # Docs can be exported on their own; derive the narrative rows directly
    # from the workbook in that case.
    from app.ingestion.excel_menu import build_menu_datasets

    return build_menu_datasets()["menu_items"]


def export_docs_json() -> dict[str, int]:
    """Write ``source_documents.json`` and ``document_chunks.json``."""
    settings = get_settings()
    docx_path = Path(settings.data_dir) / PROFILE_DOCX_FILENAME
    if not docx_path.exists():
        raise FileNotFoundError(
            f"DOCX missing at {docx_path}. Place {PROFILE_DOCX_FILENAME} in data/."
        )

    menu_rows = _menu_rows_for_narratives()
    source_documents = [
        _profile_source_document(docx_path),
        _menus_narrative_source_document(menu_rows),
    ]
    chunks = _build_profile_chunks(docx_path) + _build_menu_narrative_chunks(menu_rows)
    write_collection("source_documents", source_documents)
    write_collection("document_chunks", chunks)
    return {
        "source_documents": len(source_documents),
        "document_chunks": len(chunks),
    }


async def ingest_all_docs(db=None) -> dict[str, int]:
    """Export DOCX/menu narratives to JSON, then load that JSON into MongoDB."""
    from app.database import get_db
    from app.ingestion.json_ingest import ingest_json_domain

    export_docs_json()
    return await ingest_json_domain(db or get_db(), "docs")


__all__ = [
    "PROFILE_DOCX_FILENAME",
    "export_docs_json",
    "ingest_all_docs",
]
